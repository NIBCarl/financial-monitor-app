/**
 * PDF documents.
 *
 * HTML → PDF through `expo-print`, then straight to the share sheet. Everything the treasurer
 * would otherwise copy out by hand (a borrower's statement, the month's report) becomes a file
 * they can send, print or file.
 *
 * Layout rules that matter in practice: A4 with real margins, zebra rows so `₱` figures do not
 * run together, and a footer with the generation date so a printed page can be traced back.
 */

const SKY = '#0284c7';
const DEEP = '#0c4a6e';
const SLATE = '#334155';

/** Escapes any text that goes into the HTML shell. */
function esc(value: unknown): string {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

