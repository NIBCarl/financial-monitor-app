/** Renders HTML to a PDF file and hands it to the share sheet. */
async function sharePdf(html: string, dialogTitle: string): Promise<void> {
  const { uri } = await Print.printToFileAsync({ html });
  if (!(await Sharing.isAvailableAsync())) {
    throw new Error(`The PDF was created at ${uri} but this device cannot share files.`);
  }
  await Sharing.shareAsync(uri, {
    mimeType: 'application/pdf',
    dialogTitle,
    UTI: 'com.adobe.pdf',
  });
}

const AGING_LABEL: Record<string, string> = {
  DUE_SOON: 'Due within 7 days',
  CURRENT: 'Due later',
  '1-30': '1–30 days late',
  '31-60': '31–60 days late',
  '61-90': '61–90 days late',
  '90+': 'Over 90 days late',
};

const CATEGORY_LABEL: Record<string, string> = {
  LOAN_REPAYMENT: 'Loan repayment',
  LOAN_DISBURSEMENT: 'Loan disbursement',
  DONATION: 'Donation',
  MEMBERSHIP_DUES: 'Membership dues',
  EXPENSE: 'Operating expense',
  OTHER: 'Other',
};


