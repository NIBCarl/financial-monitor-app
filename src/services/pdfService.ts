export interface MonthlyReportInput {
  orgName: string;
  currencySymbol: string;
  monthLabel: string;
  /** `YYYY-MM` the report covers; used to find the published seal. Defaults to today's month. */
  period?: string;
}

/** The month-end report: cash, portfolio health, arrears, forecast, expenses and activity. */
export async function exportMonthlyReportPdf(input: MonthlyReportInput): Promise<void> {
  const [metrics, aging, risk, forecast, transactions, expenseRows] = await Promise.all([
    ledgerRepo.getMetrics(),
    reportsRepo.getAgingSchedule(),
    reportsRepo.getPortfolioRisk(),
    reportsRepo.getForecast(3),
    ledgerRepo.getTransactions(200),
    ledgerRepo.getExpenseBreakdown(),
  ]);

  const symbol = input.currencySymbol;
  const money = (v: number) => formatCurrency(v, symbol);

  const arrears = aging.filter((a) => a.bucket !== 'CURRENT' && a.bucket !== 'DUE_SOON');
  const arrearsTotal = canonicalMoney(arrears.reduce((sum, a) => sum + a.amount, 0));

  const agingRows = aging
    .map(
      (a) => `<tr>
        <td>${esc(AGING_LABEL[a.bucket])}</td>
        <td class="num">${a.installmentCount}</td>
        <td class="num">${a.borrowerCount}</td>
        <td class="num">${money(a.amount)}</td>
      </tr>`
    )
    .join('');

  const forecastRows = forecast.length
    ? forecast
        .map(
          (f) => `<tr>
            <td>${esc(f.period)}</td>
            <td class="num">${f.installmentCount}</td>
            <td class="num">${money(f.expected)}</td>
          </tr>`
        )
        .join('')
    : '<tr><td colspan="3">No scheduled collections yet.</td></tr>';

  const expenseList = expenseRows.length
    ? expenseRows
        .map(
          (e) => `<tr>
            <td>${esc(e.description || '—')}</td>
            <td>${esc(CATEGORY_LABEL[e.category] ?? e.category)}</td>
            <td class="num">${money(e.total)}</td>
          </tr>`
        )
        .join('')
    : '<tr><td colspan="3">No expenses recorded.</td></tr>';

  const recentRows = transactions
    .slice(0, 25)
    .map(
      (t) => `<tr>
        <td>${esc(formatDbDate(t.transactionDate))}</td>
        <td>${esc(CATEGORY_LABEL[t.category] ?? t.category)}${t.voidedAt ? ' <span class="warn">(void)</span>' : ''}</td>
        <td>${esc(t.description || '—')}</td>
        <td class="num">${t.type === 'INFLOW' ? '+' : '−'}${money(t.amount)}</td>
      </tr>`
    )
    .join('');

  // The seal the members were given for this month, if the treasurer has closed it.
  let seal: LedgerSeal | null = null;
  try {
    seal = await sealRepo.getLatestForPeriod(input.period ?? localToday().slice(0, 7));
  } catch {
    // A database without the seals table still produces a valid report.
    seal = null;
  }

  const body = `
    <h2>Cash position</h2>
    <div class="cards">
      <div class="card"><div class="k">Liquid cash</div><div class="v">${money(metrics.liquidCash)}</div></div>
      <div class="card"><div class="k">Total in</div><div class="v">${money(metrics.totalInflows)}</div></div>
      <div class="card"><div class="k">Total out</div><div class="v">${money(metrics.totalOutflows)}</div></div>
    </div>

    <h2>Portfolio</h2>
    <div class="cards">
      <div class="card"><div class="k">Outstanding</div><div class="v">${money(metrics.outstandingPrincipal)}</div></div>
      <div class="card"><div class="k">Overdue</div><div class="v ${metrics.overdueAmount > 0 ? 'warn' : 'ok'}">${money(metrics.overdueAmount)}</div></div>
      <div class="card"><div class="k">Portfolio at risk</div><div class="v">${risk.parPercent.toFixed(1)}%</div></div>
    </div>
    <table class="totals">
      <tr><td class="label">Active loans</td><td class="value">${risk.activeLoanCount}</td></tr>
      <tr><td class="label">Loans behind schedule</td><td class="value">${risk.atRiskLoanCount}</td></tr>
      <tr><td class="label">Borrowers with an active loan</td><td class="value">${metrics.activeBorrowersCount}</td></tr>
      <tr><td class="label">Expected interest (unearned)</td><td class="value">${money(metrics.expectedInterest)}</td></tr>
      <tr><td class="label">Collections this month</td><td class="value">${money(metrics.totalCollectedThisMonth)}</td></tr>
    </table>

    <h2>Aging of receivables</h2>
    <table>
      <thead><tr><th>Bucket</th><th class="num">Installments</th><th class="num">Borrowers</th><th class="num">Amount</th></tr></thead>
      <tbody>${agingRows}</tbody>
    </table>
    <table class="totals">
      <tr><td class="label grand">Total arrears</td><td class="value grand">${money(arrearsTotal)}</td></tr>
    </table>

    <h2>Expected collections — coming months</h2>
    <table>
      <thead><tr><th>Month</th><th class="num">Installments</th><th class="num">Expected</th></tr></thead>
      <tbody>${forecastRows}</tbody>
    </table>

    <h2>Expenses by category</h2>
    <table>
      <thead><tr><th>Description</th><th>Category</th><th class="num">Amount</th></tr></thead>
      <tbody>${expenseList}</tbody>
    </table>

    <h2>Recent ledger activity</h2>
    <table>
      <thead><tr><th>Date</th><th>Category</th><th>Description</th><th class="num">Amount</th></tr></thead>
      <tbody>${recentRows}</tbody>
    </table>

    <h2>Published seal for this month</h2>
    ${
      seal
        ? `<table class="totals">
             <tr><td class="label">Seal code</td><td class="value">${esc(seal.sealCode)}</td></tr>
             <tr><td class="label">Sealed on</td><td class="value">${esc(formatDbDate(seal.createdAt))}</td></tr>
             <tr><td class="label">Entries covered</td><td class="value">${seal.auditCount}</td></tr>
             <tr><td class="label">Chain head</td><td class="value mono">${esc(seal.chainHead.slice(0, 32))}…</td></tr>
           </table>
           <div class="qrrow">${toSvgRects(seal.sealCode, 132)}<div class="qrhint">Scan to compare against the seal the members received. A matching code means this report was not rewritten after the month was closed.</div></div>`
        : `<p class="note">This month has not been sealed yet. Sealing it (Reports → Sealed months) fixes the figures and prints a code the members can check.</p>`
    }
  `;

  await sharePdf(
    documentShell(
      `Monthly report — ${input.monthLabel}`,
      input.orgName,
      body,
      'Figures are derived from the installment schedule and the ledger. Voided entries are excluded from totals.'
    ),
    'Share monthly report'
  );
}

