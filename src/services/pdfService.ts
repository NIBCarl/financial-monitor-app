export interface StatementInput {
  borrowerId: string;
  /** When omitted, the borrower's newest loan is used. */
  loanId?: string;
  orgName: string;
  currencySymbol: string;
}

/**
 * Statement of account for one loan: the terms, the amortization schedule with what has actually
 * been paid against each installment, and the payment history including any voids.
 */
export async function exportLoanStatementPdf(input: StatementInput): Promise<void> {
  const borrower = await borrowerRepo.getById(input.borrowerId);
  if (!borrower) throw new Error('That borrower is no longer in the book.');

  const loans = await loanRepo.getLoansByBorrower(input.borrowerId);
  if (loans.length === 0) throw new Error('That borrower has no loan to report on.');

  const loan = (input.loanId ? loans.find((l) => l.id === input.loanId) : loans[0]) ?? loans[0];

  const [schedules, payments] = await Promise.all([
    loanRepo.getSchedulesByLoanId(loan.id),
    paymentRepo.getPaymentsByLoan(loan.id),
  ]);

  const symbol = input.currencySymbol;
  const money = (v: number) => formatCurrency(v, symbol);

  const scheduleRows = schedules
    .map((s) => {
      const remaining = getScheduleRemaining(s);
      const late = s.status !== 'PAID' ? getDaysLate(s.dueDate) : 0;
      const status =
        s.status === 'PAID'
          ? '<span class="pill">Paid</span>'
          : late > 0
            ? `<span class="warn">${late}d late</span>`
            : 'Pending';
      return `<tr>
        <td class="num">#${s.installmentNumber}</td>
        <td>${esc(formatDbDate(s.dueDate))}</td>
        <td class="num">${money(s.expectedAmount)}</td>
        <td class="num">${money(s.paidAmount)}</td>
        <td class="num">${money(remaining)}</td>
        <td>${status}</td>
      </tr>`;
    })
    .join('');

  const paymentRows = payments.length
    ? payments
        .map(
          (p) => `<tr>
            <td>${esc(formatDbDate(p.paidAt))}</td>
            <td>${esc(p.paymentMethod)}</td>
            <td>${esc(p.referenceNo || '—')}</td>
            <td>${p.voidedAt ? '<span class="warn">VOID</span>' : 'Posted'}</td>
            <td class="num">${p.voidedAt ? '—' : money(p.amountPaid)}</td>
          </tr>`
        )
        .join('')
    : '<tr><td colspan="5">No payments recorded yet.</td></tr>';

  const paidTotal = canonicalMoney(
    payments.filter((p) => !p.voidedAt).reduce((s, p) => s + p.amountPaid, 0)
  );

  // Penalties belong on the statement: they are money the borrower is being asked to pay, and an
  // open fine is the single most likely reason a collection visit turns into an argument.
  let penaltyRows = '<tr><td colspan="6">No penalties assessed.</td></tr>';
  let penaltyOutstanding = 0;

  try {
    const charges = await penaltyRepo.getChargesForLoan(loan.id);
    if (charges.length > 0) {
      penaltyRows = charges
        .map((charge) => {
          const open = canonicalMoney(charge.amount - charge.paidAmount);
          if (!charge.waivedAt) penaltyOutstanding = canonicalMoney(penaltyOutstanding + open);
          return `<tr>
            <td class="num">#${esc(charge.installmentNumber ?? '—')}</td>
            <td>${charge.waivedAt ? '<span class="warn">WAIVED</span>' : esc(charge.daysLate + 'd late')}</td>
            <td class="num">${money(charge.amount)}</td>
            <td class="num">${money(charge.paidAmount)}</td>
            <td class="num">${charge.waivedAt ? '—' : money(open)}</td>
            <td>${esc(charge.waivedReason || (charge.waivedAt ? 'waived' : 'assessed'))}</td>
          </tr>`;
        })
        .join('');
    }
  } catch {
    // A database without the penalty tables still produces a valid statement.
    penaltyRows = '<tr><td colspan="6">No penalties assessed.</td></tr>';
  }

  const body = `
    <h2>Borrower</h2>
    <table class="totals">
      <tr><td class="label">Name</td><td class="value">${esc(borrower.fullName)}</td></tr>
      <tr><td class="label">Phone</td><td class="value">${esc(borrower.phoneNumber)}</td></tr>
      <tr><td class="label">Address</td><td class="value">${esc(borrower.address || '—')}</td></tr>
      <tr><td class="label">Category</td><td class="value">${esc(borrower.categoryTag || 'General')}</td></tr>
    </table>

    <h2>Loan terms</h2>
    <table class="totals">
      <tr><td class="label">Loan reference</td><td class="value">${esc(loan.id)}</td></tr>
      <tr><td class="label">Principal</td><td class="value">${money(loan.principalAmount)}</td></tr>
      <tr><td class="label">Interest</td><td class="value">${esc(loan.interestRate)}% (${esc(loan.interestType)})</td></tr>
      <tr><td class="label">Schedule</td><td class="value">${esc(loan.frequency)} × ${esc(loan.termCount)}</td></tr>
      <tr><td class="label">Released</td><td class="value">${esc(formatDbDate(loan.startDate))}</td></tr>
      <tr><td class="label">Maturity</td><td class="value">${esc(formatDbDate(loan.endDate))}</td></tr>
      <tr><td class="label">Total payable</td><td class="value">${money(loan.totalPayable)}</td></tr>
      <tr><td class="label">Paid to date</td><td class="value">${money(paidTotal)}</td></tr>
      <tr><td class="label grand">Balance</td><td class="value grand">${money(loan.remainingBalance)}</td></tr>
      <tr><td class="label">Penalties outstanding</td><td class="value">${money(penaltyOutstanding)}</td></tr>
      <tr><td class="label">Total collectable</td><td class="value">${money(canonicalMoney(loan.remainingBalance + penaltyOutstanding))}</td></tr>
    </table>

    <h2>Installment schedule</h2>
    <table>
      <thead><tr><th class="num">#</th><th>Due date</th><th class="num">Expected</th><th class="num">Paid</th><th class="num">Remaining</th><th>Status</th></tr></thead>
      <tbody>${scheduleRows}</tbody>
    </table>

    <h2>Penalties assessed</h2>
    <table>
      <thead><tr><th class="num">Installment</th><th>Lateness</th><th class="num">Charged</th><th class="num">Paid</th><th class="num">Open</th><th>Note</th></tr></thead>
      <tbody>${penaltyRows}</tbody>
    </table>

    <h2>Payment history</h2>
    <table>
      <thead><tr><th>Date</th><th>Method</th><th>Reference</th><th>Status</th><th class="num">Amount</th></tr></thead>
      <tbody>${paymentRows}</tbody>
    </table>
  `;

  await sharePdf(
    documentShell(
      `Statement of account — ${loan.id}`,
      input.orgName,
      body,
      'Generated from the ledger on this device. Voided payments are listed but excluded from the balance.'
    ),
    'Share statement of account'
  );
}
